#!/usr/bin/env python3
"""Generate (or check) the root file `KAM.lean`, which imports every module of the library.

Usage:
  scripts/gen_root_imports.py          rewrite KAM.lean
  scripts/gen_root_imports.py --check  exit 1 if KAM.lean is out of date

Every `.lean` file under `KAM/` is imported, except the frozen theorem anchors in state
`DRAFT_SORRY` and their provider modules: the frozen-anchor quarantine forbids any other module
from importing them. They are still compiled by a plain `lake build`, through the library glob
`.andSubmodules KAM` in the lakefile. No module may import the root file.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = "KAM"

HEADER = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module
"""

DOC = """
/-!
# KAM

Root of the KAM formalization. This file imports every module of the library except the frozen
theorem anchors that are still `DRAFT_SORRY` and their provider modules, which the frozen-anchor
quarantine forbids importing; a plain `lake build` still compiles those through the library glob.
It is generated by `scripts/gen_root_imports.py`; do not edit it by hand, and never import it.
-/
"""


def quarantined() -> set[str]:
    """Module names of DRAFT_SORRY theorem anchors and of their provider modules."""
    import json
    manifest = ROOT / "manifest" / "frozen-anchors.json"
    out: set[str] = set()
    for anchor in json.loads(manifest.read_text(encoding="utf-8")).get("anchors", []):
        if anchor.get("kind") == "theorem" and anchor.get("state") == "DRAFT_SORRY":
            out.add(".".join(Path(anchor["path"]).with_suffix("").parts))
            out.add(anchor["implementation"]["module"])
    return out


def modules() -> list[str]:
    skip = quarantined()
    names = []
    for path in sorted((ROOT / LIB).rglob("*.lean")):
        rel = path.relative_to(ROOT).with_suffix("")
        name = ".".join(rel.parts)
        if name not in skip:
            names.append(name)
    return names


def render() -> str:
    imports = "".join(f"public import {name}\n" for name in modules())
    return HEADER + ("\n" + imports if imports else "") + DOC


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check; do not write")
    args = parser.parse_args()
    target = ROOT / f"{LIB}.lean"
    wanted = render()
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if args.check:
        if current != wanted:
            print(f"{target.name} is out of date; run scripts/gen_root_imports.py", file=sys.stderr)
            return 1
        return 0
    if current != wanted:
        target.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
