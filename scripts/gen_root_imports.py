#!/usr/bin/env python3
"""Generate (or check) the root file `KAM.lean`, which imports every module of the library.

Usage:
  scripts/gen_root_imports.py          rewrite KAM.lean
  scripts/gen_root_imports.py --check  exit 1 if KAM.lean is out of date

Every `.lean` file under `KAM/` is imported, so a plain `lake build` compiles every declaration,
including the frozen statements under `KAM/Frozen/`. No module may import the root file.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = "KAM"

HEADER = """/-
Copyright (c) 2026 Scott Armstrong. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong
-/
module
"""

DOC = """
/-!
# KAM

Root of the KAM formalization. This file imports every module of the library, so that a plain
`lake build` compiles every declaration. It is generated by `scripts/gen_root_imports.py`; do not
edit it by hand, and never import it from another module.
-/
"""


def modules() -> list[str]:
    names = []
    for path in sorted((ROOT / LIB).rglob("*.lean")):
        rel = path.relative_to(ROOT).with_suffix("")
        names.append(".".join(rel.parts))
    return names


def render() -> str:
    imports = "".join(f"public import {name}\n" for name in modules())
    return HEADER + ("\n" + imports if imports else "") + DOC


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check; do not write")
    args = parser.parse_args()
    target = ROOT / f"{LIB}.lean"
    wanted = render()
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if args.check:
        if current != wanted:
            print(f"{target.name} is out of date; run scripts/gen_root_imports.py", file=sys.stderr)
            return 1
        return 0
    if current != wanted:
        target.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
